@router.get("", response_model=ApiResponse, summary="Retrieve Verified Government Schemes")
def get_schemes(
    category: Optional[str] = Query(None, description="Filter by category e.g. Direct Benefit Transfer, Water Harvesting"),
    level: Optional[str] = Query(None, description="Filter by level: Karnataka_State or Central_Government"),
    department: Optional[str] = Query(None, description="Filter by department"),
    db: Optional[Session] = Depends(get_db)
):
    """
    Fetches the statutory catalog of verified Karnataka State and Central agricultural schemes
    along with their eligibility parameters and required documents.
    """
    schemes_data = []

    if db is not None:
        try:
            query = db.query(GovernmentScheme).filter(GovernmentScheme.is_active == True)
            if category:
                query = query.filter(GovernmentScheme.category.ilike(f"%{category}%"))
            if level:
                query = query.filter(GovernmentScheme.level == level)
            if department:
                query = query.filter(GovernmentScheme.department_en.ilike(f"%{department}%"))

            db_schemes = query.all()
            if db_schemes:
                for s in db_schemes:
                    item = SchemeResponse.model_validate(s).model_dump()
                    schemes_data.append(item)
        except Exception:
            pass

    # If database had no entries, fallback to authentic JSON catalog
    if not schemes_data:
        raw_catalog = RuleEvaluator.load_fallback_schemes()
        for raw in raw_catalog:
            if category and category.lower() not in raw.get("category", "").lower():
                continue
            if level and level.lower() != raw.get("level", "").lower():
                continue
            schemes_data.append({
                "id": raw["id"],
                "scheme_code": raw["scheme_code"],
                "name_en": raw["name_en"],
                "name_kn": raw["name_kn"],
                "department_en": raw.get("department", "Department of Agriculture"),
                "department_kn": raw.get("department_kn", "ಕೃಷಿ ಇಲಾಖೆ"),
                "category": raw.get("category", "Agriculture Welfare"),
                "level": raw.get("level", "Karnataka_State"),
                "benefit_type": "Direct_Benefit_Transfer",
                "benefit_amount_desc_en": raw.get("benefit_amount", ""),
                "benefit_amount_desc_kn": raw.get("benefit_amount", ""),
                "summary_en": raw.get("name_en", ""),
                "summary_kn": raw.get("summary_kn", ""),
                "application_portal": raw.get("portal", ""),
                "is_active": True,
                "rules": raw.get("rules", []),
                "documents": [{"document_name_en": d, "document_name_kn": d, "is_mandatory": True} for d in raw.get("documents_kn", [])]
            })

    return ApiResponse(
        success=True,
        data=schemes_data,
        message=f"Retrieved {len(schemes_data)} verified government schemes"
    )

@router.post("/recommend", response_model=ApiResponse, summary="Recommend Schemes Based on Profile")
def recommend_schemes(payload: SchemeRecommendRequest, db: Optional[Session] = Depends(get_db)):
    """
    Evaluates farmer parameters against the deterministic rule engine to discover potential schemes.
    Accepts either a registered farmer_id OR a direct profile object.
    Never asserts official government approval.
    """
    farmer_ctx = None
    farmer_id = payload.farmer_id

    # 1. Resolve farmer profile from database if farmer_id is provided
    if farmer_id:
        if db is None:
            raise HTTPException(status_code=503, detail="Database unavailable to fetch farmer profile.")
        farmer = db.query(Farmer).filter(Farmer.id == farmer_id).first()
        if not farmer:
            raise HTTPException(status_code=404, detail=f"Farmer with ID {farmer_id} not found.")

        farmer_ctx = {
            "id": farmer.id,
            "total_land_acres": float(farmer.total_land_acres or 0.0),
            "caste_category": farmer.caste_category,
            "annual_income": float(farmer.annual_income or 0.0),
            "irrigation_type": farmer.irrigation_type,
            "has_borewell": farmer.has_borewell,
            "district": farmer.district,
            "crops": [
                {
                    "crop_name": c.crop_name,
                    "crop_name_kn": c.crop_name_kn,
                    "crop_category": c.crop_category,
                    "acres": float(c.acres)
                }
                for c in farmer.crops
            ]
        }
    elif payload.profile:
        # Use directly supplied profile
        p = payload.profile
        farmer_ctx = {
            "total_land_acres": p.total_land_acres,
            "caste_category": p.caste_category,
            "annual_income": p.annual_income,
            "irrigation_type": p.irrigation_type,
            "has_borewell": p.has_borewell,
            "district": p.district,
            "crops": [c.model_dump() for c in (p.crops or [])]
        }
    else:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Either 'farmer_id' or a 'profile' object must be provided for recommendations."
        )

    # 2. Execute deterministic rule evaluation
    eval_result = RuleEvaluator.evaluate_farmer(farmer_ctx)

    # 3. Format recommendations
    recommendations: List[RecommendedScheme] = []

    # Add 100% matched schemes
    for s in eval_result["eligible_schemes"]:
        recommendations.append(
            RecommendedScheme(
                scheme_id=s["scheme_id"],
                scheme_code=s["scheme_code"],
                name_en=s["name_en"],
                name_kn=s["name_kn"],
                department_kn=s["department_kn"],
                match_score=s["match_score"],
                indicative_status="LIKELY_ELIGIBLE",
                benefit_amount_kn=s["benefit_amount_kn"],
                qualification_reasons_kn=s["qualification_reasons_kn"],
                missing_criteria_kn=[],
                required_documents_kn=s.get("required_documents_kn", []),
                how_to_apply_kn=s["how_to_apply_kn"],
                application_portal=s.get("application_portal")
            )
        )

    # Add partially eligible schemes (>= 50% match)
    for s in eval_result["partially_eligible_schemes"]:
        recommendations.append(
            RecommendedScheme(
                scheme_id=s["scheme_id"],
                scheme_code=s["scheme_code"],
                name_en=s["name_en"],
                name_kn=s["name_kn"],
                department_kn=s["department_kn"],
                match_score=s["match_score"],
                indicative_status="PARTIALLY_ELIGIBLE",
                benefit_amount_kn=s["benefit_amount_kn"],
                qualification_reasons_kn=s.get("qualification_reasons_kn", []),
                missing_criteria_kn=s.get("missing_criteria_kn", []),
                required_documents_kn=s.get("required_documents_kn", []),
                how_to_apply_kn=s["how_to_apply_kn"],
                application_portal=s.get("application_portal")
            )
        )

    response_payload = SchemeRecommendResponse(
        farmer_id=farmer_id,
        recommendations_count=len(recommendations),
        schemes=recommendations,
        statutory_disclaimer_kn=STATUTORY_DISCLAIMER_KN,
        statutory_disclaimer_en=STATUTORY_DISCLAIMER_EN
    )

    return ApiResponse(
        success=True,
        data=response_payload.model_dump(),
        message=f"Generated {len(recommendations)} potential scheme recommendations"
    )

@router.post("/check-eligibility", response_model=ApiResponse, summary="Audit-Traceable Rule Eligibility Check")
def check_eligibility(payload: SchemeCheckEligibilityRequest, db: Optional[Session] = Depends(get_db)):
    """
    Performs an audit-traceable statutory rule evaluation for a specific farmer.
    Optionally evaluates against one scheme_id or the entire catalog.
    Records evaluation trail for auditing.
    """
    if db is None:
        raise HTTPException(status_code=503, detail="Database service is unavailable.")

    farmer = db.query(Farmer).filter(Farmer.id == payload.farmer_id).first()
    if not farmer:
        raise HTTPException(status_code=404, detail=f"Farmer with ID {payload.farmer_id} not found.")

    farmer_ctx = {
        "id": farmer.id,
        "total_land_acres": float(farmer.total_land_acres or 0.0),
        "caste_category": farmer.caste_category,
        "annual_income": float(farmer.annual_income or 0.0),
        "irrigation_type": farmer.irrigation_type,
        "has_borewell": farmer.has_borewell,
        "district": farmer.district,
        "crops": [
            {
                "crop_name": c.crop_name,
                "crop_name_kn": c.crop_name_kn,
                "crop_category": c.crop_category,
                "acres": float(c.acres)
            }
            for c in farmer.crops
        ]
    }

    # Run evaluation
    eval_result = RuleEvaluator.evaluate_farmer(farmer_ctx)

    evaluations: List[EligibilityEvaluationItem] = []

    # Combine all evaluated schemes
    all_evaluated = (
        [(s, "ELIGIBLE") for s in eval_result["eligible_schemes"]] +
        [(s, "PARTIALLY_ELIGIBLE") for s in eval_result["partially_eligible_schemes"]] +
        [(s, "INELIGIBLE") for s in eval_result["ineligible_schemes"]]
    )

    for s, status_label in all_evaluated:
        if payload.scheme_id and s["scheme_id"] != payload.scheme_id:
            continue

        item = EligibilityEvaluationItem(
            scheme_id=s["scheme_id"],
            scheme_code=s["scheme_code"],
            name_en=s["name_en"],
            name_kn=s["name_kn"],
            status=status_label,
            match_score=s["match_score"],
            benefit_amount_kn=s["benefit_amount_kn"],
            satisfied_conditions_kn=s.get("qualification_reasons_kn", []),
            unsatisfied_conditions_kn=s.get("missing_criteria_kn", s.get("unmet_reasons_kn", [])),
            required_documents_kn=s.get("required_documents_kn", []),
            how_to_apply_kn=s["how_to_apply_kn"],
            application_portal=s.get("application_portal")
        )
        evaluations.append(item)

        # Record evaluation audit in DB if scheme exists in DB
        try:
            db_scheme = db.query(GovernmentScheme).filter(GovernmentScheme.id == s["scheme_id"]).first()
            if db_scheme:
                eval_record = EligibilityEvaluation(
                    farmer_id=farmer.id,
                    scheme_id=s["scheme_id"],
                    status=status_label,
                    match_score=s["match_score"],
                    reasons_json=item.satisfied_conditions_kn,
                    missing_criteria_json=item.unsatisfied_conditions_kn
                )
                db.add(eval_record)
        except Exception:
            pass

    try:
        db.commit()
    except Exception:
        db.rollback()

    response_payload = SchemeCheckEligibilityResponse(
        farmer_id=farmer.id,
        evaluated_at=datetime.now(timezone.utc),
        evaluations=evaluations,
        statutory_disclaimer_kn=STATUTORY_DISCLAIMER_KN,
        statutory_disclaimer_en=STATUTORY_DISCLAIMER_EN
    )

    return ApiResponse(
        success=True,
        data=response_payload.model_dump(),
        message="Rule-based eligibility check completed with full statutory transparency"
    )
